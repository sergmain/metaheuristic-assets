'''Deterministic simulation of the clients and transport around the server side.

The server side (module app) is attached through its ports and driven by the
logical clock. Nothing here reads a wall clock, starts a thread or does I/O.
All randomness comes from random.Random instances built from the seed.

Order of events within logical second t (fixed per seed):
  Due deliveries, client issues and the AdvanceTime call of second t form lanes:
    ('down', s)  updates arriving at station s, in transmission order
    ('up', s)    acknowledgements arriving at the server from station s, in
                 the order the station generated them
    ('client',)  SetDesiredPrice calls due at t, in generation order
    ('clock',)   the AdvanceTime(t) call
  The lanes are shuffled by a seeded generator and each lane runs in FIFO
  order. The server's sends during second t arrive at t+1 or later.
  An arriving update overwrites the station display and produces exactly one
  acknowledgement at its arrival time.
'''

import random
from collections.abc import Mapping
from dataclasses import dataclass
from typing import Optional

DOWNLINK_DELAY = (1, 12)
UPLINK_DELAY = (1, 12)
RETRANSMIT_TIMEOUT = 30
SERVER_METHODS = ('set_desired_price', 'receive_ack', 'advance_time', 'query_station')
_OUTSTANDING_NAMES = ('outstanding', 'outstanding_count', 'outstanding_records', 'records_outstanding')


@dataclass
class ClientChange:
    time: int
    station: str
    price: object
    accepted: bool = False


@dataclass
class Transmission:
    index: int
    sent_at: int
    station: str
    price: object
    dropped: bool = False
    deliver_at: Optional[int] = None
    delivered_at: Optional[int] = None


@dataclass
class Ack:
    index: int
    station: str
    sent_at: int
    dropped: bool = False
    deliver_at: Optional[int] = None
    delivered_at: Optional[int] = None


class Station:
    '''Simulated station: one display value, one acknowledgement per update.'''

    def __init__(self, name):
        self.name = name
        self.display = None
        self.received = []  # (arrival time, price) in arrival order
        self.acks = []      # Ack records in the order generated

    def receive(self, now, price):
        self.display = price
        self.received.append((now, price))


class ClientGenerator:
    '''Seeded sequence of SetDesiredPrice calls over logical seconds 1..duration.'''

    def __init__(self, rng, stations, duration, change_rate=0.4, max_burst=3, price_range=(1, 9), revisit=0.3):
        self.rng = rng
        self.stations = list(stations)
        self.duration = duration
        self.change_rate = change_rate
        self.max_burst = max_burst
        self.price_range = price_range
        self.revisit = revisit

    def generate(self):
        changes = []
        history = {s: [] for s in self.stations}
        lo, hi = self.price_range
        last = None
        for t in range(1, self.duration + 1):
            if self.rng.random() >= self.change_rate:
                continue
            if last is not None and self.rng.random() < 0.5:
                station = last
            else:
                station = self.rng.choice(self.stations)
            for _ in range(self.rng.randint(1, self.max_burst)):
                past = history[station]
                if past and self.rng.random() < self.revisit:
                    price = self.rng.choice(past)  # return to an earlier price
                else:
                    price = self.rng.randint(lo, hi)
                past.append(price)
                changes.append(ClientChange(t, station, price))
            last = station
        return changes


class Simulation:
    '''Drives an attached server through the simulated clients, stations and transport.

    server may be None (attach later), an object providing the four server
    operations, or a factory taking the send_update port and returning such an
    object. sim.send_update is the SendUpdate port and can be given to the
    server before it is built.
    '''

    def __init__(self, seed, server=None, *, stations=3, duration=60, changes=None, change_rate=0.4,
                 max_burst=3, price_range=(1, 9), loss_downlink=0.2, loss_uplink=0.2):
        names = [f'S{i}' for i in range(1, stations + 1)] if isinstance(stations, int) else list(stations)
        self.seed = seed
        self.duration = duration
        self.loss_downlink = loss_downlink
        self.loss_uplink = loss_uplink
        self.stations = {name: Station(name) for name in names}
        self.now = 0
        self.transmissions = []  # every SendUpdate call, in call order
        self.acks = []           # every acknowledgement generated by stations
        self.issued = []         # client changes delivered to the server
        self._client_rng = random.Random(f'{seed}:clients')
        self._net_rng = random.Random(f'{seed}:net')
        self._order_rng = random.Random(f'{seed}:order')
        if changes is None:
            changes = ClientGenerator(self._client_rng, names, duration, change_rate, max_burst, price_range).generate()
        self.changes = []
        for c in changes:
            change = c if isinstance(c, ClientChange) else ClientChange(*c)
            if change.time < 1 or change.station not in self.stations:
                raise ValueError(f'invalid client change: {change!r}')
            self.changes.append(change)
        self.changes.sort(key=lambda c: c.time)  # stable: generation order kept within a second
        self._next_change = 0
        self._down = []  # Transmission records awaiting delivery
        self._up = []    # Ack records awaiting delivery
        self._uplink_last = {name: 0 for name in names}
        self._server = None
        if server is not None:
            self.attach(server)

    @property
    def server(self):
        return self._server

    def attach(self, server):
        if isinstance(server, type) or not all(hasattr(server, m) for m in SERVER_METHODS):
            if not callable(server):
                raise TypeError('attach needs a server object or a factory taking send_update')
            server = server(self.send_update)
        missing = [m for m in SERVER_METHODS if not callable(getattr(server, m, None))]
        if missing:
            raise TypeError(f'server lacks {missing}')
        bind = getattr(server, 'bind_send_update', None)
        if callable(bind):
            bind(self.send_update)
        else:
            server.send_update = self.send_update
        self._server = server
        return server

    def send_update(self, station, price):
        '''SendUpdate port: records the transmission and decides its fate.'''
        if station not in self.stations:
            raise ValueError(f'unknown station {station!r}')
        tx = Transmission(len(self.transmissions), self.now, station, price)
        self.transmissions.append(tx)
        if self._net_rng.random() < self.loss_downlink:
            tx.dropped = True
        else:
            tx.deliver_at = self.now + self._net_rng.randint(*DOWNLINK_DELAY)
            self._down.append(tx)

    def _send_ack(self, station):
        ack = Ack(len(self.acks), station, self.now)
        self.acks.append(ack)
        self.stations[station].acks.append(ack)
        if self._net_rng.random() < self.loss_uplink:
            ack.dropped = True
            return
        delay = self._net_rng.randint(*UPLINK_DELAY)
        # Never overtake an earlier ack from the same station (in-order uplink).
        due = max(self.now + delay, self._uplink_last[station])
        self._uplink_last[station] = due
        ack.deliver_at = due
        self._up.append(ack)

    def _deliver_update(self, tx):
        tx.delivered_at = self.now
        self.stations[tx.station].receive(self.now, tx.price)
        self._send_ack(tx.station)

    def step(self):
        '''Advance logical time by one second and process that second.'''
        server = self._require_server()
        self.now += 1
        t = self.now
        lanes = {}
        remaining = []
        for tx in self._down:
            if tx.deliver_at == t:
                lanes.setdefault(('down', tx.station), []).append(tx)
            else:
                remaining.append(tx)
        self._down = remaining
        remaining = []
        for ack in self._up:
            if ack.deliver_at == t:
                lanes.setdefault(('up', ack.station), []).append(ack)
            else:
                remaining.append(ack)
        self._up = remaining
        while self._next_change < len(self.changes) and self.changes[self._next_change].time <= t:
            lanes.setdefault(('client',), []).append(self.changes[self._next_change])
            self._next_change += 1
        lanes[('clock',)] = [None]
        order = sorted(lanes)
        self._order_rng.shuffle(order)
        for key in order:
            for item in lanes[key]:
                if key[0] == 'down':
                    self._deliver_update(item)
                elif key[0] == 'up':
                    item.delivered_at = t
                    server.receive_ack(item.station)
                elif key[0] == 'client':
                    server.set_desired_price(item.station, item.price)
                    item.accepted = True
                    self.issued.append(item)
                else:
                    server.advance_time(t)
        return t

    def run(self, seconds):
        for _ in range(seconds):
            self.step()
        return self.now

    def run_until_quiet(self, horizon=5000):
        '''Step until nothing is in flight, no change is pending and no record is outstanding.

        Returns False if logical time reaches horizon first.
        '''
        while not self.quiet():
            if self.now >= horizon:
                return False
            self.step()
        return True

    def quiet(self):
        if self._down or self._up or self.pending_changes():
            return False
        counts = [self.outstanding(name) for name in self.stations]
        if any(c is None for c in counts):
            # Unknown QueryStation shape: an outstanding record is retransmitted at
            # least every 30 s of silence, so a 30 s window with no transmission
            # means none is outstanding.
            return not any(tx.sent_at > self.now - RETRANSMIT_TIMEOUT for tx in self.transmissions)
        return not any(counts)

    def pending_changes(self):
        return len(self.changes) - self._next_change

    def in_flight_count(self):
        return len(self._down) + len(self._up)

    def query(self, station):
        return self._require_server().query_station(station)

    def outstanding(self, station):
        '''Outstanding record count from QueryStation, or None if its shape is unrecognised.'''
        return _outstanding_of(self.query(station))

    def display(self, station):
        return self.stations[station].display

    def _require_server(self):
        if self._server is None:
            raise RuntimeError('no server attached')
        return self._server


def _outstanding_of(result):
    if isinstance(result, Mapping):
        for name in _OUTSTANDING_NAMES:
            if name in result:
                return _value(result[name])
        return None
    for name in _OUTSTANDING_NAMES:
        if hasattr(result, name):
            return _value(getattr(result, name))
    if isinstance(result, (tuple, list)) and len(result) >= 3:
        return _value(result[2])  # Interface order: desired, last sent, outstanding, stale, up-to-date
    return None


def _value(v):
    return v() if callable(v) else v
