import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))

import api_twin  # noqa: E402
from api_twin import TwinError, twin, write_twin  # noqa: E402

BASE = '''// header: ask mh.asset.call-cc_1.2, then implement with mh.asset.nrvv-implement_1.1
source "nrvv-sample-1.3" {

    variables {
        <- prompt
        <- model
    }

    ask := mh.asset.call-cc_1.2 {
        name "Ask"
        // the process timeout must be larger than timeout-sec
        meta variable-for-prompt = "prompt",
             variable-for-output = "answer",
             variable-for-model = "model",
             timeout-sec = "900"
        <- prompt, model
        -> answer: ext=".txt"
        timeout 1200
    }

    check := mh.asset.nrvv-sample-check_1.0 {
        meta variable-for-answer = "answer"
        <- answer
    }

    implement := mh.asset.nrvv-implement_1.1 {
        meta variable-for-model = "model", timeout-sec = "1800"
        <- model
    }
}
'''

TWIN = '''// API TWIN of nrvv-sample-1.3.mhsc - generated by nrvv/tools/api_twin.py (plan 052): every model call site
// on the API code of its Function, with llm_provider = "claude_api". Do not edit: regenerate from the base.

// header: ask mh.asset.call-cc_1.2, then implement with mh.asset.nrvv-implement_1.1
source "nrvv-sample-api-1.3" {

    variables {
        <- prompt
        <- model
    }

    ask := mh.asset.call-cc-api_1.0 {
        name "Ask"
        // the process timeout must be larger than timeout-sec
        meta llm_provider = "claude_api",
             variable-for-prompt = "prompt",
             variable-for-output = "answer",
             variable-for-model = "model",
             timeout-sec = "900"
        <- prompt, model
        -> answer: ext=".txt"
        timeout 1200
    }

    check := mh.asset.nrvv-sample-check_1.0 {
        meta variable-for-answer = "answer"
        <- answer
    }

    implement := mh.asset.nrvv-implement-api_1.0 {
        meta llm_provider = "claude_api",
             variable-for-model = "model", timeout-sec = "1800"
        <- model
    }
}
'''


def test_the_twin_moves_every_model_call_site_and_nothing_else():
    text, uid, sites = twin(BASE, 'nrvv-sample-1.3.mhsc')

    assert text == TWIN
    assert uid == 'nrvv-sample-api-1.3'
    assert sites == [(9, 'mh.asset.call-cc_1.2', 'mh.asset.call-cc-api_1.0'),
                     (26, 'mh.asset.nrvv-implement_1.1', 'mh.asset.nrvv-implement-api_1.0')]


def test_crlf_stays_crlf():
    text, _, _ = twin(BASE.replace('\n', '\r\n'), 'nrvv-sample-1.3.mhsc')

    assert text == TWIN.replace('\n', '\r\n')


@pytest.mark.parametrize('base, message', [
    (BASE.replace('             variable-for-model = "model",\n', ''), "no 'variable-for-model'"),
    (BASE.replace('meta variable-for-prompt', 'meta llm_provider = "cc",\n             variable-for-prompt'),
     'already carries llm_provider'),
    (BASE.replace('<- prompt, model', '<- prompt, model // mh.asset.call-cc_1.2'), 'outside a call site'),
    (BASE.replace('source "nrvv-sample-1.3"', 'source "nrvv-sample-api-1.3"'), 'already a twin'),
    (BASE.replace('mh.asset.call-cc_1.2 {', 'mh.asset.other_1.0 {').replace('mh.asset.nrvv-implement_1.1 {',
                                                                           'mh.asset.other_1.0 {'),
     'no model call site'),
    (BASE.replace('source "nrvv-sample-1.3" {\n', ''), 'no source declaration'),
])
def test_an_unexpected_shape_is_refused(base, message):
    with pytest.raises(TwinError, match=message):
        twin(base, 'nrvv-sample-1.3.mhsc')


def test_write_twin_writes_once_then_reports_unchanged_and_refuses_a_different_twin(tmp_path):
    base = tmp_path / 'nrvv-sample-1.3.mhsc'
    base.write_text(BASE, encoding='utf-8', newline='')

    path, state, _ = write_twin(str(base))
    assert (os.path.basename(path), state) == ('nrvv-sample-api-1.3.mhsc', 'written')
    assert (tmp_path / 'nrvv-sample-api-1.3.mhsc').read_text(encoding='utf-8', newline='') == TWIN
    assert write_twin(str(base))[1] == 'unchanged'

    (tmp_path / 'nrvv-sample-api-1.3.mhsc').write_text(TWIN + '// edited\n', encoding='utf-8', newline='')
    with pytest.raises(TwinError, match='bump the base version'):
        write_twin(str(base))


def test_main_reports_each_base_and_fails_when_one_is_refused(tmp_path, capsys):
    good, bad = tmp_path / 'nrvv-sample-1.3.mhsc', tmp_path / 'nrvv-plain-1.0.mhsc'
    good.write_text(BASE, encoding='utf-8', newline='')
    bad.write_text('source "nrvv-plain-1.0" {\n}\n', encoding='utf-8', newline='')

    assert api_twin.main(['api_twin.py', str(good), str(bad), '--out', str(tmp_path / 'out')]) == 1
    console = capsys.readouterr().out
    assert 'written ' in console and 'REFUSED nrvv-plain-1.0.mhsc: no model call site' in console
